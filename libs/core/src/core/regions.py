"""대여소를 11개 지역센터 중 하나에 근사 배정한다.

지역센터의 정확한 관할 경계(어느 구·동까지 담당하는지)는 공개 자료로 확인되지
않는다. 그래서 각 대여소를 좌표상 가장 가까운 지역센터에 배정하는 최근접
(nearest-neighbor) 근사를 쓴다 — 실제 관할과 다를 수 있으며(특히 두 지역센터
사이 경계 근처), 대여소를 현장 단위로 의미 있게 묶어서 보여주는 용도로만 쓴다.

좌표는 서울시설공단 내부 자료를 전재한 GitHub 이슈 #60의 센터 위치를 기준으로
2026-08-27 공개 주소 검색 결과와 대조했다. 천왕은 과거 자료의 시설 주소를 같은
시설의 현재 공식 주소인 서울특별시 구로구 오리로 1156으로 정규화했다. 이는
오류동 354-4와 천왕동 280-11의 직접 지번 변경 이력을 뜻하지 않는다. 따라서 이
값은 현장 측량 좌표나 공식 관할 경계가 아니다.
"""

import math

DISPATCH_CENTERS: list[tuple[str, float, float]] = [
    ("상암", 37.5682884450841, 126.897273034482),
    ("중랑", 37.5555327873138, 127.060282308271),
    ("세종로", 37.5733740925746, 126.975914786533),
    ("도봉", 37.6897145198121, 127.044811612656),
    ("훈련원", 37.5673947880932, 127.003544929278),
    ("이수", 37.4837582703213, 126.982400620133),
    ("개화", 37.5779633833321, 126.798145262463),
    ("천왕", 37.4871043528524, 126.839135337627),
    ("영남", 37.5194560071619, 126.902588056831),
    ("천호", 37.5385036573159, 127.125111736335),
    ("학여울", 37.4957890132293, 127.071795320112),
]


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """두 좌표 사이의 거리를 구면 거리(km)로 계산한다."""
    r = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    d_phi = math.radians(lat2 - lat1)
    d_lambda = math.radians(lon2 - lon1)
    a = math.sin(d_phi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(d_lambda / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def nearest_region(lat: float, lon: float) -> str:
    """대여소 좌표에서 가장 가까운 지역센터의 이름을 반환한다."""
    return min(
        DISPATCH_CENTERS,
        key=lambda center: _haversine_km(lat, lon, center[1], center[2]),
    )[0]
